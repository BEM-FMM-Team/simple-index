#!/usr/bin/env python3
# usage: python3 gen_index.py
# writes simple/index.html and simple/<package>/index.html (PEP 503) from the
# wheels in simple/<package>/, rerun after adding or removing a wheel
import hashlib
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent / "simple"
HEADER = "<!DOCTYPE html>\n<!-- generated by gen_index.py, do not edit -->\n<html>\n<body>\n"
FOOTER = "</body>\n</html>\n"


def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def write(path, links):
    body = "".join(f'<a href="{escape(href)}">{escape(text)}</a><br>\n' for href, text in links)
    path.write_text(HEADER + body + FOOTER)


packages = sorted(p for p in ROOT.iterdir() if p.is_dir())
for pkg in packages:
    wheels = sorted(pkg.glob("*.whl"))
    write(pkg / "index.html", [(f"{w.name}#sha256={sha256(w)}", w.name) for w in wheels])
write(ROOT / "index.html", [(f"{p.name}/", p.name) for p in packages])
